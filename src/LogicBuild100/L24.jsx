import React from 'react'

// অ্যালগরিদম (Algorithm)

// • ধাপ ১: শুরু (Start)
// প্রোগ্রাম বা প্রক্রিয়াটি শুরু করি।
// • ধাপ ২: ইনপুট গ্রহণ (Input)
// ব্যবহারকারীর কাছ থেকে শেষ সীমার মান N ইনপুট হিসেবে গ্রহণ করি।
// • ধাপ ৩: প্রারম্ভিক মান নির্ধারণ (Initialization)
// একটি কাউন্টার ভেরিয়েবল i নিই এবং এর প্রারম্ভিক মান i = 2 নির্ধারণ করি (যেহেতু প্রথম জোড় সংখ্যা ২)।
// • ধাপ ৪: শর্ত যাচাই (Condition Check)
// যদি i <= N হয়, তবে ৫ নং ধাপে যাই। অন্যথায় ৭ নং ধাপে (শেষ ধাপে) চলে যাই।
// • ধাপ ৫: সংখ্যা প্রিন্ট করা (Print)
// বর্তমান i এর মান স্ক্রিনে প্রিন্ট বা প্রদর্শন করি।
// • ধাপ ৬: মান বৃদ্ধি করা (Increment)
// পরবর্তী জোড় সংখ্যাটি পাওয়ার জন্য i এর মান ২ বাড়িয়ে দিই, অর্থাৎ i = i + 2 করি এবং পুনরায় ৪ নং ধাপে ফিরে যাই।
// • ধাপ ৭: শেষ (End)
// প্রোগ্রামটি শেষ করি



const L24 = () => {
    const EvennumberPrint = (number) => {
        let numbers = []; // জোড় সংখ্যাগুলো রাখার জন্য খালি অ্যারে

        // for লুপ ২ থেকে শুরু হয়ে ১ থেকে N পর্যন্ত জোড় সংখ্যাগুলো নিবে
        for (let i = 2; i <= number; i += 2) {
            numbers.push(
                <span key={i} style={{ marginRight: '10px' }}>
                    {i}
                </span>
            );
        }
        
        return numbers; // সম্পূর্ণ অ্যারেটি রিটার্ন করা হলো
    }
    
    // ১০০ পর্যন্ত জোড় সংখ্যা বের করার জন্য ফাংশনটি কল করা হলো
    const print = EvennumberPrint(100)

    return (
        <div>
            <h1>১ থেকে N পর্যন্ত জোড় সংখ্যা প্রিন্ট করা (For Loop)</h1>
            <div style={{ wordBreak: 'break-word', lineHeight: '2' }}>
                {print}
            </div>
        </div>
    )
}

export default L24
